import { createWriteStream } from "node:fs";
import { mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import PDFDocument from "pdfkit";
import { storagePath } from "./storage.js";

export type InvoicePdfInput = {
  number: string;
  fullName: string;
  email: string;
  amountCents: number;
  currency: string;
  issuedAt: Date;
};

/** Writes a simple invoice PDF under storage/invoices/ and returns the relative storage key. */
export async function writeInvoicePdf(input: InvoicePdfInput): Promise<string> {
  const relKey = `invoices/${input.number}.pdf`;
  const full = storagePath(relKey);
  await mkdir(dirname(full), { recursive: true });

  const amount = (input.amountCents / 100).toFixed(2);
  const currency = input.currency.toUpperCase();

  await new Promise<void>((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 50 });
    const stream = createWriteStream(full);
    doc.pipe(stream);
    doc.fontSize(22).text("NIVO", { continued: false });
    doc.moveDown(0.5);
    doc.fontSize(16).text("Service fee invoice");
    doc.moveDown();
    doc.fontSize(11).fillColor("#333");
    doc.text(`Invoice: ${input.number}`);
    doc.text(`Issued: ${input.issuedAt.toISOString().slice(0, 10)}`);
    doc.moveDown();
    doc.text(`Bill to: ${input.fullName}`);
    doc.text(`Email: ${input.email}`);
    doc.moveDown();
    doc.text(`Description: NIVO service fee (partner products billed separately)`);
    doc.text(`Amount: ${currency} ${amount}`);
    doc.moveDown(2);
    doc.fontSize(9).fillColor("#666").text("This document is generated by NIVO for your records.");
    doc.end();
    stream.on("finish", () => resolve());
    stream.on("error", reject);
  });

  return relKey;
}

export function invoicePdfAbsolutePath(storageKey: string): string {
  return storagePath(...storageKey.split("/"));
}

